/**
 * Decode CP437 (DOS/IBM PC) encoded buffer to UTF-8 string
 * @param buffer - Buffer containing CP437 encoded data
 * @returns UTF-8 string
 */
export function decodeCP437(buffer: Buffer): string {
  let result = '';

  for (let i = 0; i < buffer.length; i++) {
    const byte = buffer[i];

    if (byte < 128) {
      // Standard ASCII
      result += String.fromCharCode(byte);
    } else {
      // Extended CP437 character
      result += CP437_TO_UNICODE[byte] || '?';
    }
  }

  return result;
}
